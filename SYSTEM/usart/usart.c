void USART1_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART1)
    {
        if ((USART1_RX_STA & 0x8000) == 0) // ????δ???
        {
            if (USART1_RX_STA & 0x4000) // ??? 0x0d
            {
                if (aRxBuffer1[0] != 0x0a)
                    USART1_RX_STA = 0; // ????????
                else
                    USART1_RX_STA |= 0x8000; // ???????
            }
            else // δ??? 0x0d
            {
                if (aRxBuffer1[0] == 0x0d)
                    USART1_RX_STA |= 0x4000;
                else
                {
                    USART1_RX_BUF[USART1_RX_STA & 0x3FFF] = aRxBuffer1[0];
                    USART1_RX_STA++;
                    if (USART1_RX_STA > (USART_REC_LEN - 1))
                        USART1_RX_STA = 0; // ????????
                }
            }
        }

        /* ???????????????? */
        HAL_UART_Receive_IT(&UART1_Handler, (uint8_t *)aRxBuffer1, RXBUFFERSIZE);
    }
}


